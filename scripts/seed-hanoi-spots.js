async function main() {
  console.log(`Seeding ${spots.length} spots for Hanoi...`);
  let created = 0;
  let skipped = 0;

  for (const spot of spots) {
    const { tags, subcategory, email, isActive, isFeatured, ...spotData } = spot;
    try {
      const existing = await prisma.spot.findFirst({ where: { cityId: CITY_ID, slug: spotData.slug } });
      if (existing) {
        console.log(`SKIP  ${spotData.slug}`);
        skipped++;
        continue;
      }
      await prisma.spot.create({
        data: {
          ...spotData,
          cityId: CITY_ID,
          published: true,
          tags: { create: tags.map(tag => ({ tag })) },
        },
      });
      console.log(`OK    ${spotData.slug}`);
      created++;
    } catch (e) {
      console.log(`FAIL  ${spotData.slug}: ${e.message}`);
    }
  }

  console.log(`\nDone. Created: ${created} | Skipped: ${skipped}`);
  await prisma.$disconnect();
}

main().catch(e => { console.error(e); process.exit(1); });


