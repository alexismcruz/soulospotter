async function main() {
  console.log("🌱 Seeding Marrakech spots...\n");
  let created = 0, skipped = 0;

  for (const spot of SPOTS) {
    const exists = await prisma.spot.findFirst({ where: { slug: spot.slug } });
    if (exists) { console.log(`  ⏭️  Skipped (exists): ${spot.name}`); skipped++; continue; }

    await prisma.spot.create({
      data: {
        name: spot.name,
        slug: spot.slug,
        cityId: CITY_ID,
        category: spot.category,
        description: spot.description,
        address: spot.address,
        googleMapsUrl: spot.googleMapsUrl,
        website: spot.website,
        phone: spot.phone,
        priceRange: spot.priceRange,
        rating: spot.rating,
        published: spot.published,
        tags: {
          create: spot.tags.map(tag => ({ tag }))
        }
      }
    });
    console.log(`  ✅ Created: ${spot.name}`);
    created++;
  }

  console.log(`\n✅ Done! Created: ${created} | Skipped: ${skipped} | Total: ${SPOTS.length}`);
  await prisma.$disconnect();
}

main().catch((e) => { console.error("❌", e.message); process.exit(1); });
